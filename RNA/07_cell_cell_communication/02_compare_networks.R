#!/usr/bin/env Rscript
# Export differential communication and three outgoing patterns.

library(CellChat)
library(dplyr)
library(tidyr)
proj_dir <- Sys.getenv("PROJ_DIR")
stopifnot(nzchar(proj_dir))
out <- file.path(proj_dir, "data/RNA/output/cellchat")
objects <- lapply(c("WT", "AD"), function(d) readRDS(file.path(out, paste0(d, ".rds"))))
names(objects) <- c("WT", "AD")
keys <- c("source", "target", "interaction_name", "pathway_name", "annotation")
tables <- lapply(objects, function(x) subsetCommunication(x)[, c(keys, "prob")])
diff <- full_join(tables$AD, tables$WT, by=keys, suffix=c("_AD", "_WT"))
diff <- diff %>% mutate(prob_AD=replace_na(prob_AD, 0), prob_WT=replace_na(prob_WT, 0), delta=prob_AD-prob_WT)
write.csv(diff, file.path(out, "ligand_receptor_differences.csv"), row.names=FALSE)
top <- diff %>% filter(source == "CPEC-1", target != source) %>% arrange(desc(abs(delta))) %>% head(20)
write.csv(top, file.path(out, "cpec1_top20.csv"), row.names=FALSE)
write.csv(objects$AD@net$weight - objects$WT@net$weight, file.path(out, "weight_difference.csv"))
wt_strength <- sort(apply(objects$WT@netP$prob, 3, sum), decreasing=TRUE)
signals <- names(head(wt_strength, 30))
writeLines(signals, file.path(out, "control_top30_pathways.txt"))
for (d in names(objects)) {
    pdf(file.path(out, paste0(d, "_pattern_selection.pdf")), width=7, height=4)
    selectK(objects[[d]], pattern="outgoing")
    dev.off()
    set.seed(0)
    cc <- identifyCommunicationPatterns(objects[[d]], pattern="outgoing", k=3)
    cells <- cc@netP$pattern$outgoing$pattern$cell %>% group_by(CellGroup) %>% slice_max(Contribution, n=1, with_ties=FALSE) %>% ungroup()
    pathways <- cc@netP$pattern$outgoing$pattern$signaling %>% filter(Signaling %in% signals) %>% group_by(Signaling) %>% slice_max(Contribution, n=1, with_ties=FALSE) %>% ungroup()
    write.csv(cells, file.path(out, paste0(d, "_cell_patterns.csv")), row.names=FALSE)
    write.csv(pathways, file.path(out, paste0(d, "_pathway_patterns.csv")), row.names=FALSE)
    saveRDS(cc, file.path(out, paste0(d, "_patterns.rds")))
}
wt <- read.csv(file.path(out,"WT_pathway_patterns.csv"))
ad <- read.csv(file.path(out,"AD_pathway_patterns.csv"))
shared <- merge(wt,ad,by="Signaling",suffixes=c("_WT","_AD"))
labels <- sort(unique(as.character(wt$Pattern)))
ad_labels <- sort(unique(as.character(ad$Pattern)))
stopifnot(length(labels) == 3, length(ad_labels) == 3)
permutations <- rbind(c(1,2,3),c(1,3,2),c(2,1,3),c(2,3,1),c(3,1,2),c(3,2,1))
scores <- apply(permutations,1,function(p) {
    map <- setNames(labels[p],ad_labels)
    sum(map[as.character(shared$Pattern_AD)] == as.character(shared$Pattern_WT))
})
map <- setNames(labels[permutations[which.max(scores),]],ad_labels)
write.csv(data.frame(AD_pattern=names(map),WT_aligned_pattern=unname(map)),file.path(out,"AD_pattern_alignment.csv"),row.names=FALSE)
for (kind in c("cell","pathway")) {
    file <- file.path(out,paste0("AD_",kind,"_patterns.csv"))
    table <- read.csv(file)
    table$Pattern <- unname(map[as.character(table$Pattern)])
    write.csv(table,file,row.names=FALSE)
}
